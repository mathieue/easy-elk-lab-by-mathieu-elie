"""PostgreSQL logs of the shop database server db-01.

Log format: log_line_prefix = '%m [%p] %q%u@%d ' (timestamp, process id, then user and
database for client sessions), with log_connections, log_disconnections,
log_checkpoints, log_lock_waits and log_min_duration_statement = 500ms.

Normal activity follows the shop traffic (same daily pattern as the apache dataset):
web servers connect and disconnect, some queries are slow, a few errors happen, and
autovacuum runs. A reporting job runs every night around 02:00 local time, and a
checkpoint is logged every 5 minutes.

Before and during each apache outage, the database is the cause:
  - from 5 minutes before the outage: lock waits and very slow queries pile up;
  - during the outage: the failing web server cannot connect any more
    ("sorry, too many clients already"), which explains its 5xx errors.
"""

import time
from datetime import datetime, timezone

from datasets.apache import Apache, Weighted, CATEGORIES, SEARCH_TERMS
from datasets.company import DB_NAME, SERVERS, WEB_SERVERS, WEB_WEIGHTS, ip

DATA_STREAM = "logs-postgresql.log-lab"
DATABASE = DB_NAME
VERSION = "17.6"
CHECKPOINT_EVERY = 300
CHECKPOINTER_PID = 812
INCIDENT_LEAD_SECONDS = 300

HOST_IPS = {name: server["ip"] for name, server in SERVERS.items()}
WEB_HOSTS = WEB_SERVERS
REPORTING_IP = ip("intranet-01")

# Share of normal activity by kind of log line.
NORMAL_MIX = {
    "connection": 0.30,
    "disconnection": 0.30,
    "slow_query": 0.28,
    "autovacuum": 0.08,
    "unique_violation": 0.025,
    "statement_timeout": 0.015,
}

TABLES = ["orders", "order_items", "cart_items", "products", "stock", "customers", "sessions"]


def shop_query(rng):
    term = rng.choice(SEARCH_TERMS).replace("+", " ")
    pid = rng.randint(1000, 1599)
    return rng.choice([
        f"SELECT p.id, p.name, p.price, s.quantity FROM products p JOIN stock s ON s.product_id = p.id "
        f"WHERE p.category = '{rng.choice(CATEGORIES)}' ORDER BY p.popularity DESC LIMIT 48",
        f"SELECT id, name, price FROM products WHERE name ILIKE '%{term}%' OR description ILIKE '%{term}%' "
        f"ORDER BY popularity DESC LIMIT 24",
        f"SELECT o.id, o.created_at, o.total FROM orders o WHERE o.customer_id = {rng.randint(1, 250000)} "
        f"ORDER BY o.created_at DESC",
        f"SELECT * FROM cart_items ci JOIN products p ON p.id = ci.product_id WHERE ci.cart_id = {rng.randint(1, 900000)}",
        f"UPDATE stock SET quantity = quantity - {rng.randint(1, 3)} WHERE product_id = {pid}",
    ])


def reporting_query(rng):
    return rng.choice([
        "SELECT date_trunc('day', created_at) AS day, count(*), sum(total) FROM orders "
        "WHERE created_at > now() - interval '30 days' GROUP BY 1 ORDER BY 1",
        "SELECT p.category, sum(oi.quantity * oi.price) FROM order_items oi JOIN products p ON p.id = oi.product_id "
        "GROUP BY p.category ORDER BY 2 DESC",
        "SELECT customer_id, count(*) FROM orders WHERE created_at > now() - interval '1 year' "
        "GROUP BY customer_id HAVING count(*) > 10",
    ])


def session_time(seconds):
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    return f"{int(hours)}:{int(minutes):02d}:{secs:06.3f}"


class Postgresql:
    name = "postgresql"
    data_stream = DATA_STREAM
    template_name = "easy-elk-postgresql-log"

    def __init__(self, seed, utc_offset_hours=1, rate=1.0):
        self.seed = seed
        self.base_rate = rate
        self.utc_offset = int(utc_offset_hours * 3600)
        # Traffic shape and outages come from the apache dataset (same seed).
        self.apache = Apache(seed=seed, utc_offset_hours=utc_offset_hours, rate=rate)
        self.web_pick = Weighted(WEB_HOSTS, WEB_WEIGHTS)

    # ------------------------------------------------------------ Elasticsearch / Kibana objects

    def index_template(self):
        return {
            "index_patterns": [DATA_STREAM],
            "data_stream": {},
            "priority": 500,
            "_meta": {"description": "PostgreSQL logs generated by easy-elk-lab datagen"},
            "template": {
                "settings": {"number_of_shards": 1, "number_of_replicas": 0},
                "mappings": {
                    "date_detection": False,
                    "dynamic_templates": [
                        {"strings_as_keyword": {
                            "match_mapping_type": "string",
                            "mapping": {"type": "keyword", "ignore_above": 1024},
                        }},
                    ],
                    "properties": {
                        "@timestamp": {"type": "date"},
                        "message": {"type": "match_only_text"},
                        "data_stream": {"properties": {
                            "type": {"type": "constant_keyword"},
                            "dataset": {"type": "constant_keyword"},
                            "namespace": {"type": "constant_keyword"},
                        }},
                        "event": {"properties": {"duration": {"type": "long"}}},
                        "process": {"properties": {"pid": {"type": "long"}}},
                        "client": {"properties": {"ip": {"type": "ip"}, "port": {"type": "long"}}},
                        "host": {"properties": {"ip": {"type": "ip"}}},
                        "postgresql": {"properties": {"log": {"properties": {
                            "query": {"type": "match_only_text",
                                      "fields": {"keyword": {"type": "keyword", "ignore_above": 1024}}},
                            "query_duration_ms": {"type": "float"},
                        }}}},
                    },
                },
            },
        }

    def data_view(self):
        return {
            "id": "easy-elk-postgresql-log",
            "title": DATA_STREAM,
            "name": "Database logs",
            "timeFieldName": "@timestamp",
        }

    # ------------------------------------------------------------ rates

    def incident(self, second):
        """(phase, outage) where phase is "before" or "during" an apache outage, else (None, None)."""
        outage = self.apache.active("outage", second)
        if outage:
            return "during", outage
        outage = self.apache.active("outage", second + INCIDENT_LEAD_SECONDS)
        if outage and second < outage["start"]:
            return "before", outage
        return None, None

    def rates(self, second):
        traffic = self.base_rate * self.apache.base_factor(second)
        rates = {kind: traffic * share for kind, share in NORMAL_MIX.items()}

        hour = ((second + self.utc_offset) % 86400) / 3600
        if 2 <= hour < 2.5:
            rates["reporting_query"] = self.base_rate * 0.5

        # Incidents keep a fixed intensity, whatever DATAGEN_RATE is.
        phase, _ = self.incident(second)
        if phase == "before":
            rates["lock_wait"] = 0.2
            rates["incident_slow_query"] = 0.3
        elif phase == "during":
            rates["too_many_clients"] = 1.0
            rates["incident_slow_query"] = 0.3
            rates["lock_wait"] = 0.1
        return rates

    def rate(self, second):
        return sum(self.rates(second).values())

    # ------------------------------------------------------------ events

    def event(self, rng, ts):
        rates = self.rates(int(ts))
        kinds = list(rates)
        kind = Weighted(kinds, [rates[k] for k in kinds]).pick(rng)
        return getattr(self, f"log_{kind}")(rng, ts)

    def scheduled(self, rng, second):
        """Checkpoints: "starting" every 5 minutes, "complete" about 27 seconds later."""
        phase = second % CHECKPOINT_EVERY
        if phase == 0:
            return [self.doc(second + 0.002, CHECKPOINTER_PID, "LOG", "checkpoint starting: time")]
        if phase == 27:
            buffers = rng.randint(800, 9000)
            write = round(buffers / 330, 3)
            return [self.doc(
                second + rng.random(), CHECKPOINTER_PID, "LOG",
                f"checkpoint complete: wrote {buffers} buffers ({buffers / 163.84:.1f}%); "
                f"0 WAL file(s) added, 0 removed, {rng.randint(1, 4)} recycled; write={write} s, "
                f"sync={rng.uniform(0.002, 0.08):.3f} s, total={write + rng.uniform(0.01, 0.1):.3f} s; "
                f"sync files={rng.randint(20, 90)}, longest={rng.uniform(0.001, 0.02):.3f} s, "
                f"average={rng.uniform(0.0005, 0.003):.3f} s; distance={buffers * 8} kB, estimate={buffers * 9} kB",
            )]
        return []

    def session(self, rng, host=None, user="shop_app"):
        host = host or self.web_pick.pick(rng)
        ip = REPORTING_IP if user == "reporting" else HOST_IPS[host]
        return {"pid": rng.randint(20000, 99999), "user": user, "ip": ip, "port": rng.randint(32768, 60999)}

    def log_connection(self, rng, ts):
        s = self.session(rng)
        return self.doc(ts, s["pid"], "LOG",
                        f"connection authorized: user={s['user']} database={DATABASE} application_name=shop-web",
                        session=s, event_type=["connection", "start"])

    def log_disconnection(self, rng, ts):
        s = self.session(rng)
        return self.doc(ts, s["pid"], "LOG",
                        f"disconnection: session time: {session_time(rng.lognormvariate(3, 1.5))} "
                        f"user={s['user']} database={DATABASE} host={s['ip']} port={s['port']}",
                        session=s, event_type=["connection", "end"])

    def slow(self, rng, ts, session, query, duration_ms):
        return self.doc(ts, session["pid"], "LOG",
                        f"duration: {duration_ms:.3f} ms  statement: {query}",
                        session=session, query=query, duration_ms=duration_ms)

    def log_slow_query(self, rng, ts):
        return self.slow(rng, ts, self.session(rng), shop_query(rng), 500 + rng.lognormvariate(6, 0.8))

    def log_reporting_query(self, rng, ts):
        return self.slow(rng, ts, self.session(rng, user="reporting"), reporting_query(rng),
                         rng.uniform(8000, 45000))

    def log_incident_slow_query(self, rng, ts):
        _, outage = self.incident(int(ts))
        return self.slow(rng, ts, self.session(rng, host=outage["host"]), shop_query(rng),
                         rng.uniform(5000, 30000))

    def log_autovacuum(self, rng, ts):
        table = rng.choice(TABLES)
        pages = rng.randint(200, 20000)
        removed = rng.randint(0, pages // 10)
        return self.doc(ts, rng.randint(20000, 99999), "LOG",
                        f'automatic vacuum of table "{DATABASE}.public.{table}": index scans: 1\n'
                        f"\tpages: {removed} removed, {pages - removed} remain, {pages} scanned (100.00% of total)\n"
                        f"\ttuples: {rng.randint(0, 50000)} removed, {rng.randint(10000, 2000000)} remain, "
                        f"0 are dead but not yet removable\n"
                        f"\tsystem usage: CPU: user: {rng.uniform(0, 0.5):.2f} s, system: {rng.uniform(0, 0.1):.2f} s, "
                        f"elapsed: {rng.uniform(0.05, 4):.2f} s")

    def log_unique_violation(self, rng, ts):
        s = self.session(rng)
        customer = rng.randint(1000, 99999)
        query = (f"INSERT INTO customers (email, created_at) VALUES ('user{customer}@example.com', now())")
        return self.doc(ts, s["pid"], "ERROR",
                        'duplicate key value violates unique constraint "customers_email_key"',
                        session=s, query=query, sql_state="23505",
                        extra_lines=[f"DETAIL:  Key (email)=(user{customer}@example.com) already exists.",
                                     f"STATEMENT:  {query}"])

    def log_statement_timeout(self, rng, ts):
        s = self.session(rng)
        query = shop_query(rng)
        return self.doc(ts, s["pid"], "ERROR", "canceling statement due to statement timeout",
                        session=s, query=query, sql_state="57014", extra_lines=[f"STATEMENT:  {query}"])

    def log_lock_wait(self, rng, ts):
        _, outage = self.incident(int(ts))
        s = self.session(rng, host=outage["host"])
        holder = rng.randint(20000, 99999)
        product = rng.randint(1000, 1100)
        query = f"UPDATE stock SET quantity = quantity - 1 WHERE product_id = {product}"
        return self.doc(ts, s["pid"], "LOG",
                        f"process {s['pid']} still waiting for ShareLock on transaction "
                        f"{rng.randint(4000000, 4100000)} after {1000 + rng.uniform(0, 5):.3f} ms",
                        session=s, query=query,
                        extra_lines=[f"DETAIL:  Process holding the lock: {holder}. Wait queue: {s['pid']}.",
                                     f'CONTEXT:  while updating tuple ({rng.randint(1, 900)},{rng.randint(1, 40)}) '
                                     f'in relation "stock"',
                                     f"STATEMENT:  {query}"])

    def log_too_many_clients(self, rng, ts):
        _, outage = self.incident(int(ts))
        s = self.session(rng, host=outage["host"])
        return self.doc(ts, s["pid"], "FATAL", "sorry, too many clients already",
                        session=s, sql_state="53300", event_type=["connection", "denied"])

    # ------------------------------------------------------------ document

    def doc(self, ts, pid, level, text, session=None, query=None, duration_ms=None, sql_state=None,
            extra_lines=None, event_type=None):
        stamp = time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(ts)) + f".{int(ts * 1000) % 1000:03d} UTC"
        prefix = f"{stamp} [{pid}] " + (f"{session['user']}@{DATABASE} " if session else "")
        lines = [f"{prefix}{level}:  {text}"] + [f"{prefix}{line}" for line in (extra_lines or [])]

        error = level in ("ERROR", "FATAL")
        doc = {
            "@timestamp": datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z"),
            "message": "\n".join(lines),
            "data_stream": {"type": "logs", "dataset": "postgresql.log", "namespace": "lab"},
            "event": {
                "dataset": "postgresql.log",
                "kind": "event",
                "category": ["database"],
                "type": event_type or (["error"] if error else ["info"]),
                "outcome": "failure" if error else "success",
            },
            "log": {"level": level},
            "host": {"name": "db-01", "ip": [HOST_IPS["db-01"]]},
            "service": {"type": "postgresql", "name": "postgresql", "version": VERSION},
            "process": {"pid": pid},
            "postgresql": {"log": {}},
        }
        if session:
            doc["user"] = {"name": session["user"]}
            doc["client"] = {"ip": session["ip"], "port": session["port"]}
            doc["postgresql"]["log"]["database"] = DATABASE
        if query:
            doc["postgresql"]["log"]["query"] = query
            doc["postgresql"]["log"]["query_step"] = "statement"
        if duration_ms is not None:
            doc["postgresql"]["log"]["query_duration_ms"] = round(duration_ms, 3)
            doc["event"]["duration"] = int(duration_ms * 1_000_000)
        if sql_state:
            doc["postgresql"]["log"]["sql_state_code"] = sql_state
            doc["error"] = {"code": sql_state, "message": text}
        if not doc["postgresql"]["log"]:
            del doc["postgresql"]
        return doc
