"""Host metrics of the shop servers, like the Metricbeat "system" module.

Every DATAGEN_METRICS_INTERVAL seconds (60 by default), each server reports one
document per metricset: cpu, memory, load, network, filesystem. The values are not
random walks: they follow the shop traffic (same daily pattern as the apache dataset)
and react to its incidents:
  - during an apache outage, the failing web server is saturated (CPU close to 100 %,
    high load) and the database server is heavily loaded too;
  - disks fill up during the week and are cleaned up every Sunday night.

DATAGEN_RATE does not change these metrics: servers do not get busier because the
lab generates more log lines.
"""

import os
from datetime import datetime, timezone

from datasets.apache import Apache
from datasets.company import MONITORED_SERVERS, SERVERS as COMPANY_SERVERS, UBUNTU

DATA_STREAM = "metrics-system.host-lab"
GIB = 1024 ** 3

OS = UBUNTU

# name, IP, CPU cores, memory (GiB), role, disks (from the company description)
SERVERS = [
    (name, s["ip"], s["cores"], s["memory_gib"], s["role"], s["disks"])
    for name, s in ((name, COMPANY_SERVERS[name]) for name in MONITORED_SERVERS)
]
# Share of the shop traffic handled by each web server.
WEB_SHARE = {name: s["traffic_share"] for name, s in COMPANY_SERVERS.items() if s["role"] == "web"}


def pct(value):
    return round(min(max(value, 0.0), 1.0), 4)


class Metrics:
    name = "metrics"
    data_stream = DATA_STREAM
    template_name = "easy-elk-system-metrics"

    def __init__(self, seed, utc_offset_hours=1, rate=1.0):
        self.seed = seed
        self.utc_offset = int(utc_offset_hours * 3600)
        self.interval = max(10, int(os.environ.get("DATAGEN_METRICS_INTERVAL", "60")))
        # Traffic shape and outages come from the apache dataset (same seed).
        self.apache = Apache(seed=seed, utc_offset_hours=utc_offset_hours, rate=rate)

    # ------------------------------------------------------------ Elasticsearch / Kibana objects

    def index_template(self):
        return {
            "index_patterns": [DATA_STREAM],
            "data_stream": {},
            "priority": 500,
            "_meta": {"description": "Host metrics generated by easy-elk-lab datagen"},
            "template": {
                "settings": {"number_of_shards": 1, "number_of_replicas": 0},
                "mappings": {
                    "date_detection": False,
                    "dynamic_templates": [
                        {"percentages": {"path_match": "*.pct", "mapping": {"type": "scaled_float", "scaling_factor": 1000}}},
                        {"strings_as_keyword": {
                            "match_mapping_type": "string",
                            "mapping": {"type": "keyword", "ignore_above": 1024},
                        }},
                    ],
                    "properties": {
                        "@timestamp": {"type": "date"},
                        "data_stream": {"properties": {
                            "type": {"type": "constant_keyword"},
                            "dataset": {"type": "constant_keyword"},
                            "namespace": {"type": "constant_keyword"},
                        }},
                        "host": {"properties": {
                            "ip": {"type": "ip"},
                            "cpu": {"properties": {"usage": {"type": "scaled_float", "scaling_factor": 1000}}},
                            "network": {"properties": {
                                "ingress": {"properties": {"bytes": {"type": "long"}, "packets": {"type": "long"}}},
                                "egress": {"properties": {"bytes": {"type": "long"}, "packets": {"type": "long"}}},
                            }},
                        }},
                        "system": {"properties": {
                            "load": {"properties": {
                                "1": {"type": "scaled_float", "scaling_factor": 100},
                                "5": {"type": "scaled_float", "scaling_factor": 100},
                                "15": {"type": "scaled_float", "scaling_factor": 100},
                                "norm": {"properties": {
                                    "1": {"type": "scaled_float", "scaling_factor": 100},
                                    "5": {"type": "scaled_float", "scaling_factor": 100},
                                    "15": {"type": "scaled_float", "scaling_factor": 100},
                                }},
                            }},
                        }},
                    },
                },
            },
        }

    def data_view(self):
        return {
            "id": "easy-elk-system-metrics",
            "title": DATA_STREAM,
            "name": "Host metrics",
            "timeFieldName": "@timestamp",
        }

    # ------------------------------------------------------------ generation

    def rate(self, second):
        """No random events: all documents are emitted at fixed times (see scheduled)."""
        return 0.0

    def event(self, rng, ts):
        raise NotImplementedError("metrics only has scheduled documents")

    def scheduled(self, rng, second):
        if second % self.interval:
            return []
        traffic = self.apache.base_factor(second)  # ~1 on average, 0.2 at night, ~1.6 at peak
        outage = self.apache.active("outage", second)
        docs = []
        for index, server in enumerate(SERVERS):
            ts = second + index * 0.001
            docs.extend(self.server_docs(rng, ts, second, server, traffic, outage))
        return docs

    def server_docs(self, rng, ts, second, server, traffic, outage):
        name, ip, cores, memory_gib, role, mounts = server

        # ---- CPU (share of all cores, 0..1)
        if role == "web":
            load = 0.05 + 0.22 * traffic * WEB_SHARE[name] / 0.4
            saturated = outage is not None and outage["host"] == name
            if saturated:
                load = 0.92
        else:
            load = 0.08 + 0.18 * traffic
            saturated = False
            if outage is not None:
                load = 0.75
        cpu = pct(load + rng.gauss(0, 0.02))
        user, system_, iowait = cpu * 0.72, cpu * 0.22, cpu * 0.06
        if role == "db" and outage is not None:
            iowait, user = cpu * 0.30, cpu * 0.50

        # ---- memory
        base_mem = 0.45 if role == "web" else 0.70
        mem_used = pct(base_mem + 0.08 * traffic + (0.2 if saturated else 0) + rng.gauss(0, 0.01))
        mem_total = memory_gib * GIB

        # ---- network (bytes during the interval)
        if role == "web":
            egress = int(traffic * WEB_SHARE[name] * 2.5e6 * self.interval * max(rng.gauss(1, 0.08), 0.1))
            ingress = int(egress * 0.08)
        else:
            ingress = int(traffic * 4e5 * self.interval * max(rng.gauss(1, 0.08), 0.1))
            egress = int(ingress * 3.5)
        if saturated:
            egress //= 4  # errors are small pages

        # ---- load average (normalized by cores)
        load1 = round(cpu * cores * (1.6 if saturated else 1.0) + abs(rng.gauss(0, 0.1)), 2)
        load5 = round(load1 * 0.9, 2)
        load15 = round(load1 * 0.8, 2)

        host = {"name": name, "hostname": name, "architecture": "x86_64", "os": OS, "ip": [ip]}

        def doc(metricset, fields, extra_host=None):
            return {
                "@timestamp": datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z"),
                "data_stream": {"type": "metrics", "dataset": "system.host", "namespace": "lab"},
                "event": {"dataset": f"system.{metricset}", "module": "system", "kind": "metric"},
                "metricset": {"name": metricset, "period": self.interval * 1000},
                "service": {"type": "system"},
                "host": {**host, **(extra_host or {})},
                "system": {metricset: fields},
            }

        docs = [
            doc("cpu", {
                "cores": cores,
                "total": {"pct": round(cpu * cores, 4), "norm": {"pct": cpu}},
                "user": {"pct": round(user * cores, 4), "norm": {"pct": pct(user)}},
                "system": {"pct": round(system_ * cores, 4), "norm": {"pct": pct(system_)}},
                "iowait": {"pct": round(iowait * cores, 4), "norm": {"pct": pct(iowait)}},
                "idle": {"pct": round((1 - cpu) * cores, 4), "norm": {"pct": pct(1 - cpu)}},
            }, {"cpu": {"usage": cpu}}),
            doc("memory", {
                "total": mem_total,
                "used": {"bytes": int(mem_total * min(mem_used + 0.15, 0.99)), "pct": pct(mem_used + 0.15)},
                "actual": {"used": {"bytes": int(mem_total * mem_used), "pct": mem_used},
                           "free": int(mem_total * (1 - mem_used))},
                "free": int(mem_total * (1 - min(mem_used + 0.15, 0.99))),
            }),
            doc("load", {"1": load1, "5": load5, "15": load15, "cores": cores,
                         "norm": {"1": round(load1 / cores, 3), "5": round(load5 / cores, 3),
                                  "15": round(load15 / cores, 3)}}),
            doc("network", {"name": "eth0"}, {"network": {
                "ingress": {"bytes": ingress, "packets": ingress // 900 + 1},
                "egress": {"bytes": egress, "packets": egress // 1200 + 1},
            }}),
        ]

        # ---- filesystems: fill up during the week, cleaned up on Sunday night
        local = second + self.utc_offset
        week = 7 * 86400
        # Epoch day 0 is a Thursday: shift so the cycle restarts on Monday 03:00 local time.
        week_progress = ((local - 4 * 86400 - 3 * 3600) % week) / week
        for mount, device, size_gib, base_used, growth in mounts:
            used = pct(base_used + growth * week_progress + rng.gauss(0, 0.002))
            total = size_gib * GIB
            docs.append(doc("filesystem", {
                "mount_point": mount,
                "device_name": device,
                "type": "ext4",
                "total": total,
                "used": {"bytes": int(total * used), "pct": used},
                "free": int(total * (1 - used)),
                "available": int(total * (1 - used) * 0.95),
            }))
        return docs
